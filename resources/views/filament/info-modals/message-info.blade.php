<div class="space-y-4">
    <div class="bg-blue-50 p-4 rounded-lg">
        <h3 class="font-semibold text-blue-800 mb-2">Was ist die Mitteilung?</h3>
        <p class="text-blue-700">
            Die Mitteilung ist ein optionaler Text, der dem Zahlenden angezeigt wird. 
            Sie hilft bei der Identifikation des Zahlungsgrunds und erscheint auf dem Einzahlungsschein.
        </p>
    </div>

    <div class="space-y-3">
        <h4 class="font-semibold">📝 Beispiele für Mitteilungen:</h4>
        
        <div class="grid gap-3">
            <div class="bg-green-50 p-3 rounded border-l-4 border-green-400">
                <div class="font-mono text-sm bg-white p-2 rounded">Rechnung vom 13.10.2023</div>
                <p class="text-green-700 text-xs mt-1">✓ Einfach und klar</p>
            </div>
            
            <div class="bg-green-50 p-3 rounded border-l-4 border-green-400">
                <div class="font-mono text-sm bg-white p-2 rounded">Auftrag Nr. 2023-1045</div>
                <p class="text-green-700 text-xs mt-1">✓ Mit Auftragsnummer</p>
            </div>
            
            <div class="bg-green-50 p-3 rounded border-l-4 border-green-400">
                <div class="font-mono text-sm bg-white p-2 rounded">Dienstleistung Oktober 2023</div>
                <p class="text-green-700 text-xs mt-1">✓ Mit Zeitraum</p>
            </div>
            
            <div class="bg-green-50 p-3 rounded border-l-4 border-green-400">
                <div class="font-mono text-sm bg-white p-2 rounded">Projekt ABC - Phase 1</div>
                <p class="text-green-700 text-xs mt-1">✓ Mit Projektbezug</p>
            </div>
            
            <div class="bg-green-50 p-3 rounded border-l-4 border-green-400">
                <div class="font-mono text-sm bg-white p-2 rounded">Mitgliedsbeitrag 2024</div>
                <p class="text-green-700 text-xs mt-1">✓ Für Vereine/Verbände</p>
            </div>
        </div>
    </div>

    <div class="bg-yellow-50 p-4 rounded-lg">
        <h4 class="font-semibold text-yellow-800 mb-2">⚠️ Wichtige Hinweise:</h4>
        <ul class="text-yellow-700 text-sm space-y-1">
            <li>• Maximal 140 Zeichen erlaubt</li>
            <li>• Erscheint auf dem gedruckten Einzahlungsschein</li>
            <li>• Wird in der E-Banking Überweisung angezeigt</li>
            <li>• Keine strukturierten Daten (dafür "Rechnungsinformationen" verwenden)</li>
        </ul>
    </div>

    <div class="bg-gray-50 p-4 rounded-lg">
        <h4 class="font-semibold text-gray-800 mb-2">💡 Best Practices:</h4>
        <ul class="text-gray-700 text-sm space-y-1">
            <li>• Kurz und prägnant formulieren</li>
            <li>• Datum oder Referenznummer einschließen</li>
            <li>• Firmenname ist nicht nötig (steht bereits im Creditor-Feld)</li>
            <li>• Bei wiederkehrenden Zahlungen: Zeitraum angeben</li>
        </ul>
    </div>
